/**
 * Represents the keyboard input state of the game.
 * Stores whether the relevant control keys are currently pressed.
 */
class Keyboard {
  /**
   * Indicates whether the left movement key is pressed.
   * @type {boolean}
   */
  LEFT = false;

  /**
   * Indicates whether the right movement key is pressed.
   * @type {boolean}
   */
  RIGHT = false;

  /**
   * Indicates whether the up movement key is pressed.
   * @type {boolean}
   */
  UP = false;

  /**
   * Indicates whether the down movement key is pressed.
   * @type {boolean}
   */
  DOWN = false;

  /**
   * Indicates whether the F attack key is pressed.
   * @type {boolean}
   */
  F = false;

  /**
   * Indicates whether the E attack key is pressed.
   * @type {boolean}
   */
  E = false;
}
